/** Per vue-i18n locale code (see locales/index.ts). */
export const nexusMessages: Record<string, Messages> = {
  en,
  zhHans: zhcn,
  zhHant: zhtw,
}

export const nexusEnglish = en

type Dict = { [key: string]: unknown }

const isDict = (v: unknown): v is Dict => typeof v === 'object' && v !== null && !Array.isArray(v)

/** Deep merge (b wins) without mutating either argument. */
export const deepMerge = <T extends Dict>(a: T, b: Dict): T => {
  const out: Dict = { ...a }
  for (const [k, v] of Object.entries(b)) {
    out[k] = isDict(v) && isDict(out[k]) ? deepMerge(out[k] as Dict, v) : v
  }
  return out as T
}

/** Upstream locale messages + nexus additions (English for untranslated locales). */
export const withNexus = <T extends Dict>(code: string, messages: T): T =>
  deepMerge(messages, (nexusMessages[code] ?? en) as unknown as Dict)
